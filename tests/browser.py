from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    c=b.new_context(viewport={'width':428,'height':926})
    page=c.new_page()
    page.goto('http://localhost:8765/cat.svg')
    for n in [192,512]:
        page.set_viewport_size({'width':n,'height':n})
        page.screenshot(path=f'app/icon{n}.png')
    page.set_viewport_size({'width':428,'height':926})
    page.goto('http://localhost:8765')
    page.evaluate('navigator.serviceWorker.ready')
    page.get_by_role('button',name='e2',exact=True).click()
    page.get_by_role('button',name='e4',exact=True).click()
    page.wait_for_function("document.querySelector('#status').textContent==='Tu turno'")
    print('Worker:', page.locator('#history').inner_text(),page.locator('#review').inner_text())
    assert page.locator('#review').inner_text()
    c.set_offline(True)
    page.reload()
    assert 'e4' in page.locator('#history').inner_text()
    page.locator('#fresh').click()
    page.get_by_role('button',name='d2',exact=True).click()
    page.get_by_role('button',name='d4',exact=True).click()
    page.wait_for_function("document.querySelector('#status').textContent==='Tu turno'")
    assert page.locator('#review').inner_text()
    print('Offline:', page.locator('#history').inner_text())
    b.close()
